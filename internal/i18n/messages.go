// ResolveLocale 根据请求解析语言
func ResolveLocale(c *gin.Context) string {
	if c == nil {
		return LocaleZH
	}
	if lang := strings.TrimSpace(c.Query("lang")); lang != "" {
		return normalizeLocale(lang)
	}
	if lang := strings.TrimSpace(c.GetHeader("X-Lang")); lang != "" {
		return normalizeLocale(lang)
	}
	accept := strings.TrimSpace(c.GetHeader("Accept-Language"))
	if accept == "" {
		return LocaleZH
	}
	parts := strings.Split(accept, ",")
	if len(parts) == 0 {
		return LocaleZH
	}
	return normalizeLocale(parts[0])
}

// T 获取翻译文本
func T(locale, key string) string {
	if locale == "" {
		locale = LocaleZH
	}
	if bundle, ok := messages[locale]; ok {
		if msg, ok := bundle[key]; ok {
			return msg
		}
	}
	if bundle, ok := messages[LocaleZH]; ok {
		if msg, ok := bundle[key]; ok {
			return msg
		}
	}
	return key
}

// Sprintf 获取带参数的翻译文本
func Sprintf(locale, key string, args ...interface{}) string {
	return fmt.Sprintf(T(locale, key), args...)
}

func normalizeLocale(locale string) string {
	l := strings.ToLower(strings.TrimSpace(locale))
	switch {
	case strings.HasPrefix(l, "zh-tw"), strings.HasPrefix(l, "zh-hk"), strings.HasPrefix(l, "zh-mo"):
		return LocaleTW
	case strings.HasPrefix(l, "zh"):
		return LocaleZH
	case strings.HasPrefix(l, "en"):
		return LocaleEN
	// 印尼语：浏览器发 id / id-ID；历史旧码 in 仍被部分 Java/Android 客户端使用
	case strings.HasPrefix(l, "id"), strings.HasPrefix(l, "in-"), l == "in":
		return LocaleID
	default:
		return LocaleZH
	}
}
